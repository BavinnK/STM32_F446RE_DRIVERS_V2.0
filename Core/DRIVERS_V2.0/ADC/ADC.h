#ifndef ADC_H
#define ADC_H

#include "stdint.h"
#include "stm32f446xx.h"
#include "GPIO.h"

///////////////////////////////////////////////////////////////////////////////////////////////////
// ENUMS
///////////////////////////////////////////////////////////////////////////////////////////////////

typedef enum {
	ADC_POLLING=0,
	ADC_INTERRUPT,
	ADC_DMA
}adc_mode_t;

typedef enum{
	BIT_12=0,
	BIT_10,
	BIT_8,
	BIT_6
}adc_res_t;

///////////////////////////////////////////////////////////////////////////////////////////////////
// END ENUMS
///////////////////////////////////////////////////////////////////////////////////////////////////

///////////////////////////////////////////////////////////////////////////////////////////////////
// STRUCTS
///////////////////////////////////////////////////////////////////////////////////////////////////

typedef struct{
	adc_res_t resolution;
	uint8_t channel;
	uint8_t sample;

	adc_mode_t mode;
}adc_config_t;

///////////////////////////////////////////////////////////////////////////////////////////////////
// END STRUCTS
///////////////////////////////////////////////////////////////////////////////////////////////////


///////////////////////////////////////////////////////////////////////////////////////////////////
// FUNCTION PROTOTYPES
///////////////////////////////////////////////////////////////////////////////////////////////////

void ADCx_init(ADC_TypeDef *adc,GPIO_TypeDef *port,uint8_t pin,uint8_t adc_channel, adc_config_t *config);
void ADCx_chn_config(ADC_TypeDef *adc,uint8_t channel,uint8_t rank);
uint16_t ADCx_read(ADC_TypeDef *adc);
void ADCx_sequence_length(ADC_TypeDef *adc,uint8_t len);
void ADCx_start(ADC_TypeDef *adc);



///////////////////////////////////////////////////////////////////////////////////////////////////
// END FUNCTION PROTOTYPES
///////////////////////////////////////////////////////////////////////////////////////////////////


#endif
